// Copies the agency identity (decision X32) into the extension pages as code: the two typefaces as one
// generated stylesheet of data URIs, the ChatGoose logo and two scenes of the goose as JSX. The sources
// archive and the XPI take no font or image files (tools/archive-check), and a page renders no markup
// from strings (tools/gates), hence modules. The source is agency-site, the brand's home: its
// `pnpm brand` writes brand/out, its `pnpm brand:inline-fonts` writes the font block.
// Usage: node tools/brand/sync.ts [path to agency-site]   (default ~/code/1-platform/agency-site)

import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';

import { REPO_ROOT } from '../lib/paths.ts';

const SITE = process.argv[2] ?? `${homedir()}/code/1-platform/agency-site`;
const OUT = `${REPO_ROOT}packages/ui/src/pages/brand/`;

const HEADER = (what: string): string =>
  `// Generated by tools/brand/sync.ts from agency-site brand/out (${what}); do not edit by hand.\n` +
  `// The brand's rules and files: ~/code/1-platform/agency-site (README «Brand», AGENTS.md «Do not add»).\n`;

// ── typefaces ──
const fonts = readFileSync(`${SITE}/brand/out/kit/gosling-fonts-inline.css`, 'utf8')
  .split('\n')
  .filter((line) => line.startsWith('@font-face'))
  .join('\n');
if (!fonts.includes("font-family:'Literata'") || !fonts.includes("font-family:'Golos Text'")) throw new Error('brand sync: the font block has no Literata or Golos Text');
writeFileSync(
  `${OUT}fonts.ts`,
  `${HEADER('kit/gosling-fonts-inline.css')}` +
    `// Literata 800 at optical size 24 and Golos Text 400–700, Latin and Cyrillic, cut down by agency-site and embedded:\n` +
    `// a page adopts it like any sheet of ours, and nothing is fetched from anywhere (the fonts are in the package).\n\n` +
    `import { type StyleSource } from '../../kit';\n\n` +
    `export const FONTS_SOURCE: StyleSource = {\n  id: 'pg-fonts',\n  css: ${JSON.stringify(`${fonts}\n`)},\n};\n`,
);

// ── drawings ──
interface Drawing {
  readonly file: string;
  readonly name: string;
  readonly doc: string;
  /** The logo's word follows the theme (currentColor); the gosling keeps its colours, as on the release site (X27). */
  readonly wordmark?: boolean;
}

const DRAWINGS: readonly Drawing[] = [
  { file: 'logo-chatgoose.svg', name: 'ChatGooseLogo', doc: 'The product logo: the gosling stands on the word.', wordmark: true },
  { file: 'art/trio.svg', name: 'TrioArt', doc: 'Three goslings walk one after another, the first looks back: «Готово к смене».' },
  { file: 'art/lost.svg', name: 'LostArt', doc: 'The goose looks back: something needs the person.' },
];

const ELEMENT = /<(\/?)([a-zA-Z]+)((?:\s+[a-zA-Z:-]+="[^"]*")*)\s*(\/?)>/g;
const ATTRIBUTE = /([a-zA-Z:-]+)="([^"]*)"/g;
const ALLOWED = new Set(['svg', 'g', 'path', 'circle', 'ellipse', 'rect']);

function jsx(svg: string, drawing: Drawing): string {
  let out = '';
  let depth = 0;
  let first = true;
  for (const match of svg.matchAll(ELEMENT)) {
    const [, closing, tag = '', attrs = '', selfClosing] = match;
    if (!ALLOWED.has(tag)) throw new Error(`brand sync: ${drawing.file} has <${tag}>`);
    if (closing === '/') {
      depth -= 1;
      out += `${'  '.repeat(depth + 2)}</${tag}>\n`;
      continue;
    }
    const pairs = [...attrs.matchAll(ATTRIBUTE)].map(([, name = '', value = '']) => [name, value] as const);
    const kept = pairs.filter(([name]) => !(first && (name === 'xmlns' || name === 'role' || name === 'aria-label' || name === 'width' || name === 'height')));
    const props = kept.map(([name, value]) => (drawing.wordmark === true && name === 'fill' && value === '#1C1B17' && tag === 'path' && depth === 1 && out.split('<path').length === 1 ? `fill="currentColor" class="pg-logo__word"` : `${name}="${value}"`));
    if (first) {
      props.push('class={props.class}', 'focusable="false"', ...(drawing.wordmark === true ? ['role="img"', 'aria-label="ChatGoose"'] : ['aria-hidden="true"']));
      first = false;
    }
    out += `${'  '.repeat(depth + 2)}<${tag} ${props.join(' ')}${selfClosing === '/' ? ' />' : '>'}\n`;
    if (selfClosing !== '/') depth += 1;
  }
  if (depth !== 0) throw new Error(`brand sync: ${drawing.file} is not balanced`);
  return out;
}

let art = `${HEADER('logo-chatgoose.svg, art/trio.svg, art/lost.svg')}\nimport { type JSX } from 'preact';\n\ninterface ArtProps {\n  readonly class?: string;\n}\n`;
for (const drawing of DRAWINGS) {
  const svg = readFileSync(`${SITE}/brand/out/${drawing.file}`, 'utf8');
  art += `\n/** ${drawing.doc} */\nexport function ${drawing.name}(props: ArtProps): JSX.Element {\n  return (\n${jsx(svg, drawing).replace(/\n$/, '')}\n  );\n}\n`;
}
writeFileSync(`${OUT}art.tsx`, art);
console.log(`brand: wrote ${OUT}fonts.ts (${fonts.length} bytes of @font-face) and ${OUT}art.tsx (${DRAWINGS.length} drawings).`);
